'use strict';

/**
 * Builds a static version of the site into ./docs for GitHub Pages.
 *  - Renders the same HTML templates the server uses (includes + policy versions).
 *  - Rewrites root-absolute URLs to relative ones so the site works under
 *    https://<user>.github.io/<repo>/.
 *  - Adds the in-browser mock API (static-demo/mock-api.js) in place of the
 *    Node.js backend, and a CSP <meta> tag (GitHub Pages cannot send headers).
 */
const fs = require('node:fs');
const path = require('node:path');
const config = require('../server/config');
const { createTemplateRenderer } = require('../server/app');
const { publicConsentConfig } = require('../server/routes');

const OUT = path.join(config.rootDir, 'docs');
const PUBLIC = config.publicDir;

const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "require-trusted-types-for 'script'",
  'trusted-types bcb-cmp',
  'upgrade-insecure-requests',
].join('; ');

function htmlPages(dir, rel = '') {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    if (entry.name === 'partials' || entry.name === 'assets') return [];
    const relPath = path.join(rel, entry.name);
    if (entry.isDirectory()) return htmlPages(path.join(dir, entry.name), relPath);
    return entry.name.endsWith('.html') ? [relPath] : [];
  });
}

function build() {
  fs.rmSync(OUT, { recursive: true, force: true });
  fs.mkdirSync(OUT, { recursive: true });
  fs.cpSync(path.join(PUBLIC, 'assets'), path.join(OUT, 'assets'), { recursive: true });
  for (const file of ['mock-api.js', 'frame-guard.js']) {
    fs.copyFileSync(path.join(config.rootDir, 'static-demo', file), path.join(OUT, 'assets', 'js', file));
  }

  const mockConfig = { consent: publicConsentConfig(), admin: { username: config.admin.username, password: config.admin.password } };
  fs.writeFileSync(
    path.join(OUT, 'assets', 'js', 'mock-config.js'),
    `/* Generated by scripts/build-static.js — do not edit. */\nwindow.DEMO_MOCK_CONFIG =${JSON.stringify(mockConfig, null, 2)};\n`
  );

  const render = createTemplateRenderer();
  const pages = htmlPages(PUBLIC);
  for (const page of pages) {
    const depth = page.split(path.sep).length - 1;
    const prefix = depth ? '../'.repeat(depth) : './';
    let html = render(path.join(PUBLIC, page));
    html = html.replace(/\b(href|src|data-cmp-src)="\/(?!\/)/g, `$1="${prefix}`);
    const referrer = html.includes('name="referrer"') ? '' : '\n  <meta name="referrer" content="same-origin">';
    html = html.replace('<meta charset="utf-8">', `<meta charset="utf-8">\n  <meta http-equiv="Content-Security-Policy" content="${CSP}">${referrer}\n  <script src="${prefix}assets/js/frame-guard.js"></script>`);
    html = html.replace('</head>', `  <script src="${prefix}assets/js/mock-config.js"></script>\n  <script src="${prefix}assets/js/mock-api.js"></script>\n</head>`);
    const target = path.join(OUT, page);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, html);
  }

  // Stop GitHub Pages from running Jekyll over the output.
  fs.writeFileSync(path.join(OUT, '.nojekyll'), '');
  console.log(`Static site built: ${pages.length} pages -> ${OUT}`);
}

build();
